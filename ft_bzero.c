#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	unsigned char	*word;
	size_t			i;

	word = (unsigned char *)s;
	i = 0;
	while (i < n)
	{
		word[i] = 0;
		i++;
	}
}
